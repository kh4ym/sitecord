-- Core schema. Follows the proposal's data model (section 10), trimmed for the
-- first working version: money is integer paisa, quantities numeric(14,3),
-- submitted records are never hard-deleted, and the audit table is append-only.
--
-- What this file is: the first database migration. db/migrate.js runs it
-- once (as one script, inside a transaction) on an empty database and
-- records its name in schema_migrations so it never runs again. It creates
-- every table the app started with; later files (002, 003) only add to it.
-- Used by every server service that reads or writes data.
--
-- SQL basics used below:
--   `--` starts a comment that runs to the end of the line.
--   CREATE TABLE name ( column type constraints, ... ); defines a table.
--   Each statement ends with a semicolon.
--   Types: text (any-length string), int (32-bit integer), bigint (64-bit
--   integer), boolean, date (calendar day), timestamptz (date + time with
--   time zone), numeric(14,3) (exact decimal: 14 digits, 3 after the point),
--   double precision (floating-point number), jsonb (binary JSON).
--   Constraints: PRIMARY KEY (unique, non-null row identifier), NOT NULL
--   (value required), UNIQUE (no two rows may share it), DEFAULT x (value
--   used when an INSERT omits the column), CHECK (condition) (rows that make
--   the condition false are rejected), REFERENCES t(col) (foreign key: the
--   value must exist in table t's column col).

-- Accounts. One row per person who can sign in.
CREATE TABLE users (
  id            text PRIMARY KEY, -- UUID generated by the server (newId())
  email         text NOT NULL UNIQUE, -- required and unique: one account per email
  name          text NOT NULL, -- display name
  phone         text, -- no NOT NULL, so it may be NULL (empty)
  password_hash text NOT NULL, -- bcrypt hash, never the password itself
  -- IN ('en', 'ur') = the value must be one of the listed ones (English/Urdu).
  locale        text NOT NULL DEFAULT 'en' CHECK (locale IN ('en', 'ur')),
  -- now() is a SQL function returning the current timestamp.
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Sign-in sessions (one per signed-in browser/device).
CREATE TABLE sessions (
  id          text PRIMARY KEY,               -- sha256 of the cookie token
  -- Foreign key to users.id. ON DELETE CASCADE: deleting a user
  -- automatically deletes their sessions too.
  user_id     text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  timestamptz NOT NULL, -- after this time the session is ignored
  user_agent  text, -- browser description (first 200 chars), optional
  created_at  timestamptz NOT NULL DEFAULT now()
);
-- CREATE INDEX name ON table (columns): a lookup structure that makes
-- searching by those columns fast (here: "all sessions of a user").
CREATE INDEX sessions_user ON sessions (user_id);

-- One house-building project.
CREATE TABLE projects (
  id                  text PRIMARY KEY,
  name                text NOT NULL,
  address             text NOT NULL DEFAULT '', -- '' = empty string, not NULL
  city                text NOT NULL,
  -- Plot size codes (5 marla, 10 marla, 1 kanal); widened in 002.
  plot_size           text NOT NULL CHECK (plot_size IN ('MARLA_5', 'MARLA_10', 'KANAL_1')),
  -- BETWEEN 1 AND 5 is inclusive: 1, 2, 3, 4 or 5 floors.
  floors              int  NOT NULL CHECK (floors BETWEEN 1 AND 5),
  -- How the builder is engaged.
  contract_type       text NOT NULL CHECK (contract_type IN ('LABOUR_ONLY', 'GREY_STRUCTURE', 'TURNKEY', 'SELF_MANAGED')),
  -- Money in paisa (1/100 rupee); `>= 0` forbids negatives.
  budget_paisa        bigint NOT NULL CHECK (budget_paisa >= 0),
  start_date          date, -- optional
  planned_end_date    date, -- optional
  stage_index         int  NOT NULL DEFAULT 1, -- which construction stage is current
  stage_progress      int  NOT NULL DEFAULT 0 CHECK (stage_progress BETWEEN 0 AND 100), -- percent
  archived_at         timestamptz, -- NULL = active; a time = archived (read-only)
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);

-- Who belongs to which project, with what role.
CREATE TABLE project_members (
  project_id  text NOT NULL REFERENCES projects(id), -- foreign key to projects
  user_id     text NOT NULL REFERENCES users(id), -- foreign key to users
  role        text NOT NULL CHECK (role IN ('OWNER', 'LOCAL_REP', 'CONTRACTOR', 'SUPERVISOR', 'INSPECTOR')),
  joined_at   timestamptz NOT NULL DEFAULT now(),
  removed_at  timestamptz, -- set instead of deleting the row (keeps history)
  -- Composite primary key: the PAIR (project_id, user_id) must be unique, so
  -- a person is a member of a project at most once.
  PRIMARY KEY (project_id, user_id)
);

-- Pending invitations sent by email link.
CREATE TABLE invitations (
  id           text PRIMARY KEY,
  project_id   text NOT NULL REFERENCES projects(id),
  email        text NOT NULL, -- who was invited
  -- OWNER is not in this list: you cannot invite another owner.
  role         text NOT NULL CHECK (role IN ('LOCAL_REP', 'CONTRACTOR', 'SUPERVISOR', 'INSPECTOR')),
  token_hash   text NOT NULL UNIQUE, -- sha256 of the token in the link
  invited_by   text NOT NULL REFERENCES users(id),
  expires_at   timestamptz NOT NULL,
  accepted_at  timestamptz, -- NULL until accepted
  revoked_at   timestamptz, -- NULL unless cancelled
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- Every change to physical progress. Drives "last updated by" and the plan's actual dates.
CREATE TABLE progress_updates (
  id               text PRIMARY KEY,
  project_id       text NOT NULL REFERENCES projects(id),
  stage_index      int  NOT NULL, -- stage the update is about
  progress_before  int  NOT NULL, -- percent before
  progress_after   int  NOT NULL, -- percent after
  stage_completed  boolean NOT NULL DEFAULT false, -- true when this finished the stage
  report_id        text, -- daily report that caused it, if any (no FK here)
  note             text,
  created_by       text NOT NULL REFERENCES users(id),
  created_at       timestamptz NOT NULL DEFAULT now()
);
-- Multi-column index: fast "this project's updates, in time order".
CREATE INDEX progress_updates_project ON progress_updates (project_id, created_at);

-- Bill of quantities: the planned materials/work items with estimates.
CREATE TABLE boq_items (
  id              text PRIMARY KEY,
  project_id      text NOT NULL REFERENCES projects(id),
  code            text NOT NULL, -- short item code, unique within the project (below)
  description     text NOT NULL,
  category        text NOT NULL,
  unit            text NOT NULL, -- e.g. bags, cft, kg
  est_qty         numeric(14,3) NOT NULL CHECK (est_qty >= 0), -- estimated quantity
  est_unit_paisa  bigint NOT NULL CHECK (est_unit_paisa >= 0), -- estimated price per unit
  phase           text NOT NULL DEFAULT 'STRUCTURE' CHECK (phase IN ('STRUCTURE', 'FINISHING')),
  archived_at     timestamptz, -- soft delete
  created_at      timestamptz NOT NULL DEFAULT now(),
  -- Table-level UNIQUE over two columns: the same code can't appear twice in one project.
  UNIQUE (project_id, code)
);

-- Payment milestones agreed with the contractor.
CREATE TABLE milestones (
  id            text PRIMARY KEY,
  project_id    text NOT NULL REFERENCES projects(id),
  stage_index   int,                                   -- stage that must be complete; null = on signing
  name          text NOT NULL,
  amount_paisa  bigint NOT NULL CHECK (amount_paisa >= 0),
  -- Life cycle of a milestone.
  status        text NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED', 'REQUESTED', 'APPROVED', 'REJECTED', 'PAID')),
  requested_at  timestamptz,
  decided_at    timestamptz,
  sort          int NOT NULL DEFAULT 0 -- display order
);

-- Purchases / costs recorded on site.
CREATE TABLE expenses (
  id              text PRIMARY KEY,
  project_id      text NOT NULL REFERENCES projects(id),
  number          int  NOT NULL, -- per-project running number (P-1, P-2 ...)
  type            text NOT NULL CHECK (type IN ('MATERIAL', 'LABOUR', 'EQUIPMENT', 'TRANSPORT', 'OTHER')),
  supplier_name   text NOT NULL,
  description     text NOT NULL DEFAULT '',
  invoice_number  text,
  purchase_date   date NOT NULL,
  total_paisa     bigint NOT NULL CHECK (total_paisa >= 0), -- sum of the lines
  from_advance    boolean NOT NULL DEFAULT false, -- paid out of the contractor's advance?
  -- Workflow states.
  status          text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'QUERIED', 'APPROVED', 'REJECTED', 'VERIFIED')),
  stage_index     int,
  created_by      text NOT NULL REFERENCES users(id),
  submitted_at    timestamptz,
  decided_at      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (project_id, number) -- running number unique per project
);
-- Fast "this project's expenses with status X".
CREATE INDEX expenses_project_status ON expenses (project_id, status);

-- The individual lines (items) of an expense.
CREATE TABLE expense_lines (
  id           text PRIMARY KEY,
  -- Deleting an expense deletes its lines with it.
  expense_id   text NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
  boq_item_id  text REFERENCES boq_items(id), -- optional link to a planned item
  description  text NOT NULL,
  qty          numeric(14,3) NOT NULL CHECK (qty > 0), -- strictly positive
  unit         text NOT NULL,
  unit_paisa   bigint NOT NULL CHECK (unit_paisa >= 0),
  total_paisa  bigint NOT NULL, -- qty × unit price
  sort         int NOT NULL DEFAULT 0 -- display order
);

-- Money paid out.
CREATE TABLE payments (
  id              text PRIMARY KEY,
  project_id      text NOT NULL REFERENCES projects(id),
  number          int  NOT NULL, -- per-project running number
  type            text NOT NULL CHECK (type IN ('ADVANCE', 'MILESTONE', 'EXPENSE_SETTLEMENT', 'OTHER')),
  method          text NOT NULL CHECK (method IN ('BANK_TRANSFER', 'CASH', 'CHEQUE', 'MOBILE_WALLET')),
  payee_name      text NOT NULL,
  payee_user_id   text REFERENCES users(id), -- set when the payee has an account
  amount_paisa    bigint NOT NULL CHECK (amount_paisa > 0),
  paid_on         date NOT NULL,
  reference       text, -- e.g. bank transaction reference
  note            text,
  milestone_id    text REFERENCES milestones(id), -- set for milestone payments
  created_by      text NOT NULL REFERENCES users(id),
  confirmed_at    timestamptz, -- when the payee confirmed receipt
  confirmed_by    text REFERENCES users(id),
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (project_id, number)
);

-- The site supervisor's/contractor's daily report.
CREATE TABLE daily_reports (
  id               text PRIMARY KEY,
  project_id       text NOT NULL REFERENCES projects(id),
  author_id        text NOT NULL REFERENCES users(id),
  report_date      date NOT NULL,
  summary          text NOT NULL, -- work done
  issues           text,
  worker_count     int CHECK (worker_count >= 0), -- nullable; CHECK passes when NULL
  weather          text,
  stage_index      int NOT NULL,
  progress_before  int NOT NULL,
  progress_after   int NOT NULL,
  stage_completed  boolean NOT NULL DEFAULT false,
  status           text NOT NULL DEFAULT 'SUBMITTED' CHECK (status IN ('SUBMITTED', 'QUERIED', 'VERIFIED')),
  created_at       timestamptz NOT NULL DEFAULT now()
);
-- Fast "this project's reports by date".
CREATE INDEX daily_reports_project ON daily_reports (project_id, report_date);

-- Materials consumed, as reported in a daily report.
CREATE TABLE report_materials (
  id           text PRIMARY KEY,
  report_id    text NOT NULL REFERENCES daily_reports(id) ON DELETE CASCADE, -- deleted with its report
  boq_item_id  text NOT NULL REFERENCES boq_items(id),
  qty          numeric(14,3) NOT NULL CHECK (qty > 0)
);

-- Requests to change scope, cost or schedule.
CREATE TABLE change_requests (
  id                 text PRIMARY KEY,
  project_id         text NOT NULL REFERENCES projects(id),
  number             int  NOT NULL,
  title              text NOT NULL,
  description        text NOT NULL,
  reason             text,
  cost_impact_paisa  bigint NOT NULL DEFAULT 0, -- may be negative (a saving)
  days_impact        int NOT NULL DEFAULT 0, -- may be negative (faster)
  status             text NOT NULL DEFAULT 'SUBMITTED' CHECK (status IN ('SUBMITTED', 'QUERIED', 'APPROVED', 'REJECTED')),
  created_by         text NOT NULL REFERENCES users(id),
  decided_at         timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (project_id, number)
);

-- Quality inspections of a stage step.
CREATE TABLE inspections (
  id            text PRIMARY KEY,
  project_id    text NOT NULL REFERENCES projects(id),
  stage_index   int  NOT NULL,
  step          text NOT NULL, -- which check within the stage
  result        text NOT NULL CHECK (result IN ('PASS', 'PARTIAL', 'FAIL')),
  notes         text,
  inspector_id  text NOT NULL REFERENCES users(id),
  inspected_on  date NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Project documents (drawings, approvals, contracts...).
CREATE TABLE documents (
  id           text PRIMARY KEY,
  project_id   text NOT NULL REFERENCES projects(id),
  title        text NOT NULL,
  category     text NOT NULL CHECK (category IN ('DRAWING', 'APPROVAL', 'CONTRACT', 'RECEIPT', 'PHOTO', 'OTHER')),
  uploaded_by  text NOT NULL REFERENCES users(id),
  archived_at  timestamptz, -- soft delete
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- Original evidence files. One nullable column per target keeps real foreign keys.
CREATE TABLE evidence (
  id             text PRIMARY KEY,
  project_id     text NOT NULL REFERENCES projects(id),
  kind           text NOT NULL CHECK (kind IN ('PHOTO', 'RECEIPT', 'INVOICE', 'HANDWRITTEN_SLIP', 'DELIVERY_PHOTO', 'BANK_PROOF', 'DOCUMENT')),
  file_name      text NOT NULL, -- original name from the uploader
  mime           text NOT NULL, -- detected content type, e.g. image/jpeg
  size_bytes     int  NOT NULL,
  sha256         text NOT NULL, -- fingerprint of the file's bytes
  storage_key    text NOT NULL, -- file name on disk
  capture_mode   text NOT NULL CHECK (capture_mode IN ('IN_APP_CAMERA', 'GALLERY', 'FILE')),
  captured_at    timestamptz, -- when the device says it was taken
  received_at    timestamptz NOT NULL DEFAULT now(), -- when the server got it
  lat            double precision, -- GPS latitude
  lng            double precision, -- GPS longitude
  caption        text,
  uploaded_by    text NOT NULL REFERENCES users(id),
  -- At most one of the following is set: the record this file is attached to.
  expense_id     text REFERENCES expenses(id),
  payment_id     text REFERENCES payments(id),
  report_id      text REFERENCES daily_reports(id),
  change_id      text REFERENCES change_requests(id),
  inspection_id  text REFERENCES inspections(id),
  document_id    text REFERENCES documents(id),
  decision_id    text, -- decisions is created below, so no FK here
  -- Table-level CHECK: num_nonnulls(...) counts how many of the arguments are
  -- not NULL; `<= 1` means a file belongs to at most one record.
  CHECK (num_nonnulls(expense_id, payment_id, report_id, change_id, inspection_id, document_id, decision_id) <= 1)
);
-- Fast "all evidence of a project".
CREATE INDEX evidence_project ON evidence (project_id);
-- Fast "is this exact file (same hash) already in the project?" (duplicate detection).
CREATE INDEX evidence_sha ON evidence (project_id, sha256);

-- Approve / reject / query / verify, on any kind of record.
CREATE TABLE decisions (
  id           text PRIMARY KEY,
  project_id   text NOT NULL REFERENCES projects(id),
  -- Polymorphic link: target_type says which table, target_id which row
  -- (no foreign key is possible across several tables).
  target_type  text NOT NULL CHECK (target_type IN ('EXPENSE', 'CHANGE', 'MILESTONE', 'REPORT')),
  target_id    text NOT NULL,
  decision     text NOT NULL CHECK (decision IN ('APPROVE', 'REJECT', 'QUERY', 'VERIFY')),
  note         text,
  live_photo   boolean, -- whether a live photo accompanied a verification
  decided_by   text NOT NULL REFERENCES users(id),
  created_at   timestamptz NOT NULL DEFAULT now()
);
-- Fast "all decisions about this record".
CREATE INDEX decisions_target ON decisions (target_type, target_id);

-- Question threads, optionally about a specific record.
CREATE TABLE questions (
  id           text PRIMARY KEY,
  project_id   text NOT NULL REFERENCES projects(id),
  number       int  NOT NULL,
  -- Nullable: a general question has no target.
  target_type  text CHECK (target_type IN ('EXPENSE', 'PAYMENT', 'REPORT', 'CHANGE')),
  target_id    text,
  title        text NOT NULL,
  status       text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'ANSWERED', 'RESOLVED')),
  -- PERSON = asked by someone; RULE = raised automatically by a check.
  source       text NOT NULL DEFAULT 'PERSON' CHECK (source IN ('PERSON', 'RULE')),
  created_by   text NOT NULL REFERENCES users(id),
  resolved_at  timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (project_id, number)
);

-- Messages inside a question thread.
CREATE TABLE question_messages (
  id           text PRIMARY KEY,
  question_id  text NOT NULL REFERENCES questions(id),
  author_id    text NOT NULL REFERENCES users(id),
  body         text NOT NULL, -- the message text
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- Deterministic rule checks. They describe inconsistencies; they never accuse.
CREATE TABLE findings (
  id            text PRIMARY KEY,
  project_id    text NOT NULL REFERENCES projects(id),
  target_type   text NOT NULL, -- which kind of record was checked
  target_id     text NOT NULL, -- which record
  rule          text NOT NULL, -- which rule produced it
  severity      text NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
  message       text NOT NULL,
  status        text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'DISMISSED')),
  dismissed_by  text REFERENCES users(id),
  dismiss_note  text,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- In-app notification inbox.
CREATE TABLE notifications (
  id          text PRIMARY KEY,
  user_id     text NOT NULL REFERENCES users(id), -- recipient
  project_id  text REFERENCES projects(id), -- optional related project
  title       text NOT NULL,
  body        text,
  link        text, -- where in the app to go when clicked
  read_at     timestamptz, -- NULL = unread
  created_at  timestamptz NOT NULL DEFAULT now()
);
-- Fast "this user's notifications, newest first".
CREATE INDEX notifications_user ON notifications (user_id, created_at);

-- Hash-chained audit trail. Each event's hash covers the previous hash, so
-- editing any old event breaks every link after it.
CREATE TABLE audit_events (
  -- bigserial = bigint filled automatically from an increasing sequence.
  id           bigserial PRIMARY KEY,
  project_id   text NOT NULL REFERENCES projects(id),
  seq          int  NOT NULL, -- position in this project's chain (1, 2, 3 ...)
  actor_id     text REFERENCES users(id), -- who did it (NULL = system)
  action       text NOT NULL, -- e.g. EXPENSE_SUBMITTED
  target_type  text,
  target_id    text,
  summary      text NOT NULL, -- human-readable sentence
  payload      jsonb NOT NULL DEFAULT '{}', -- extra data as JSON; default empty object
  prev_hash    text NOT NULL, -- hash of the previous event ('GENESIS' for the first)
  hash         text NOT NULL, -- sha256 over prev_hash + this event's fields
  created_at   timestamptz NOT NULL, -- no default: the server supplies it (it is hashed)
  UNIQUE (project_id, seq) -- no two events at the same position (no forks)
);

-- A trigger function that always fails. CREATE FUNCTION name() RETURNS
-- trigger defines a function usable by triggers. The body sits between the
-- $$ ... $$ markers (dollar quoting: a string that needs no escaping) and is
-- written in PL/pgSQL (LANGUAGE plpgsql), Postgres's procedural language.
-- BEGIN ... END wraps the statements; RAISE EXCEPTION aborts with an error
-- message, which also rolls back the statement that fired the trigger.
CREATE FUNCTION audit_events_append_only() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'audit_events is append-only';
END
$$ LANGUAGE plpgsql;

-- CREATE TRIGGER: run the function above automatically BEFORE any UPDATE or
-- DELETE on audit_events, once FOR EACH ROW affected. Because the function
-- raises an error, existing audit rows can never be changed or removed;
-- only INSERT is possible.
CREATE TRIGGER audit_events_no_change
  BEFORE UPDATE OR DELETE ON audit_events
  FOR EACH ROW EXECUTE FUNCTION audit_events_append_only();
